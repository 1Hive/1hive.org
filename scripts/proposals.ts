import { lstat, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises"
import path from "node:path"
import matter from "gray-matter"
import yaml from "js-yaml"
import { remark } from "remark"
import { visit } from "unist-util-visit"
import { agentResources } from "../quartz/plugins/emitters/agentResources"

export const stages = {
  "working-draft": {
    label: "Working draft",
    description: "The problem and approach are being developed.",
  },
  "in-review": {
    label: "In review",
    description: "The document is ready for feedback from the people affected.",
  },
  stable: {
    label: "Stable",
    description:
      "The document is maintained as a settled reference. Check its separate decision record.",
  },
  archived: {
    label: "Archived",
    description:
      "The document is no longer being developed. Read its record for the reason or replacement.",
  },
} as const

const decisionLabels = {
  pending: "Pending",
  accepted: "Accepted",
  declined: "Declined",
  deferred: "Deferred",
  withdrawn: "Withdrawn",
  superseded: "Superseded",
} as const
const fundingLabels = {
  "not-requested": "Not requested",
  "not-recorded": "Not recorded",
  requested: "Requested",
  approved: "Approved",
  declined: "Declined",
} as const
const deliveryLabels = {
  "not-started": "Not started",
  "in-progress": "In progress",
  complete: "Complete",
  "not-recorded": "Not recorded",
} as const

interface RecordState<S extends string> {
  status: S
  evidence: string[]
  date?: string
}

export interface ProposalMetadata {
  id: string
  title: string
  summary: string
  stage: keyof typeof stages
  scope: string
  owner: string
  created: string
  updated: string
  decision: RecordState<keyof typeof decisionLabels> & { authority: string }
  funding: RecordState<keyof typeof fundingLabels>
  delivery: RecordState<keyof typeof deliveryLabels>
}

export interface Proposal {
  file: string
  slug: string
  metadata: ProposalMetadata
  body: string
}

export const generatedMarker =
  "<!-- Generated by scripts/generate-proposals.ts. Edit proposals/ instead. -->"
const sourcePattern = /^proposals\/(?:\d{4}|draft)-[a-z0-9]+(?:-[a-z0-9]+)*\.md$/

function object(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === "object" && !Array.isArray(value)
}

function isDate(value: unknown): value is string {
  return (
    typeof value === "string" &&
    /^\d{4}-\d{2}-\d{2}$/.test(value) &&
    !Number.isNaN(Date.parse(value)) &&
    new Date(value).toISOString().slice(0, 10) === value
  )
}

export function validateMetadata(value: unknown): string[] {
  if (!object(value)) return ["frontmatter must be a YAML object"]
  const errors: string[] = []
  const fields = [
    "id",
    "title",
    "summary",
    "stage",
    "scope",
    "owner",
    "created",
    "updated",
    "decision",
    "funding",
    "delivery",
  ]
  for (const key of Object.keys(value)) {
    if (!fields.includes(key)) errors.push(`unknown metadata field: ${key}`)
  }
  for (const key of ["id", "title", "summary", "scope", "owner"]) {
    if (typeof value[key] !== "string" || !value[key].trim() || /[\r\n]/.test(value[key])) {
      errors.push(`${key} must be a nonempty, single-line string`)
    }
  }
  if (typeof value.id !== "string" || !/^(?:\d{4}|unassigned)$/.test(value.id)) {
    errors.push('id must be a quoted four-digit number or "unassigned"')
  }
  if (typeof value.stage !== "string" || !Object.hasOwn(stages, value.stage)) {
    errors.push(`stage must be one of: ${Object.keys(stages).join(", ")}`)
  }
  for (const key of ["created", "updated"]) {
    if (!isDate(value[key])) errors.push(`${key} must be a real date in YYYY-MM-DD format`)
  }
  if (isDate(value.created) && isDate(value.updated) && value.updated < value.created) {
    errors.push("updated cannot precede created")
  }

  const records = { decision: decisionLabels, funding: fundingLabels, delivery: deliveryLabels }
  for (const [key, labels] of Object.entries(records)) {
    const record = value[key]
    if (!object(record)) {
      errors.push(`${key} must contain status and evidence`)
      continue
    }
    for (const field of Object.keys(record)) {
      if (
        !["status", "evidence", "date", ...(key === "decision" ? ["authority"] : [])].includes(
          field,
        )
      ) {
        errors.push(`unknown metadata field: ${key}.${field}`)
      }
    }
    if (typeof record.status !== "string" || !Object.hasOwn(labels, record.status)) {
      errors.push(`${key}.status must be one of: ${Object.keys(labels).join(", ")}`)
    }
    if (
      key === "decision" &&
      (typeof record.authority !== "string" ||
        !record.authority.trim() ||
        /[\r\n]/.test(record.authority))
    ) {
      errors.push("decision.authority must name the responsible process or say Unassigned")
    }
    if (
      !Array.isArray(record.evidence) ||
      !record.evidence.every((url) => {
        if (typeof url !== "string" || /[\s<>]/.test(url)) return false
        try {
          const parsed = new URL(url)
          return (
            ["https:", "http:"].includes(parsed.protocol) && !parsed.username && !parsed.password
          )
        } catch {
          return false
        }
      })
    ) {
      errors.push(`${key}.evidence must be an array of public HTTP(S) source URLs`)
    }
    const needsEvidence =
      typeof record.status === "string" &&
      !["pending", "not-requested", "not-recorded", "not-started"].includes(record.status)
    if (needsEvidence && (!Array.isArray(record.evidence) || record.evidence.length === 0)) {
      errors.push(`${key}.${record.status} requires source evidence`)
    }
    if ((needsEvidence || record.date !== undefined) && !isDate(record.date)) {
      errors.push(`${key}.date must record a real date in YYYY-MM-DD format`)
    }
    if (isDate(record.date) && isDate(value.updated) && record.date > value.updated) {
      errors.push(`${key}.date cannot be later than updated`)
    }
  }
  return errors
}

export function parseProposal(file: string, source: string): Proposal {
  if (!sourcePattern.test(file))
    throw new Error(`${file}: use a numbered or draft proposal filename`)
  const parsed = matter(source, {
    engines: { yaml: (s) => yaml.load(s, { schema: yaml.JSON_SCHEMA }) as object },
  })
  const errors = validateMetadata(parsed.data)
  if (!parsed.content.trim()) errors.push("proposal body must not be empty")
  const id = parsed.data.id
  if (
    typeof id === "string" &&
    !path.basename(file).startsWith(`${id === "unassigned" ? "draft" : id}-`)
  ) {
    errors.push("filename prefix must match id (use draft- for unassigned)")
  }
  if (errors.length) throw new Error(`${file}:\n${errors.map((e) => `  ${e}`).join("\n")}`)
  return {
    file,
    slug: file.slice(0, -3),
    metadata: parsed.data as ProposalMetadata,
    body: parsed.content.trim(),
  }
}

// Only opted-in public sources can become pages. README and TEMPLATE remain raw documents.
export async function readProposals(
  root = process.cwd(),
  resources: readonly string[] = agentResources,
): Promise<Proposal[]> {
  const files = resources.filter(
    (file) =>
      file.startsWith("proposals/") &&
      !["proposals/README.md", "proposals/TEMPLATE.md"].includes(file),
  )
  if (new Set(files).size !== files.length)
    throw new Error("Duplicate proposal file in agentResources")
  const proposals: Proposal[] = []
  const ids = new Set<string>()
  for (const file of files) {
    if (!sourcePattern.test(file)) throw new Error(`${file}: invalid allowlisted proposal path`)
    if (!(await lstat(path.join(root, file))).isFile())
      throw new Error(`${file}: proposal source must be a regular file`)
    const proposal = parseProposal(file, await readFile(path.join(root, file), "utf8"))
    if (proposal.metadata.id !== "unassigned") {
      if (ids.has(proposal.metadata.id))
        throw new Error(`${file}: duplicate proposal ID ${proposal.metadata.id}`)
      ids.add(proposal.metadata.id)
    }
    proposals.push(proposal)
  }
  return proposals.sort((a, b) => a.file.localeCompare(b.file, "en"))
}

function text(value: string): string {
  return value
    .replaceAll("&", "&amp;")
    .replaceAll("<", "&lt;")
    .replaceAll(">", "&gt;")
    .replace(/[\\`*_[\]{}()#!|]/g, "\\$&")
}

function frontmatter(data: Record<string, unknown>): string {
  return `---\n${yaml.dump(data, { lineWidth: -1 }).trim()}\n---\n\n${generatedMarker}\n\n`
}

function statusLine<S extends string>(
  name: string,
  record: RecordState<S>,
  labels: Record<S, string>,
): string {
  const evidence = record.evidence.map((url, i) => `[Source ${i + 1}](<${url}>)`).join(", ")
  return `- **${name}:** ${labels[record.status]}${record.date ? ` (${record.date})` : ""}${evidence ? `. ${evidence}` : ""}`
}

export function resolveProposalLinks(proposal: Proposal): string {
  const replacements: { start: number; end: number; value: string }[] = []
  // Parse link nodes so code examples and existing wiki links are left untouched.
  // Preserve all other source formatting, including reference links and link titles.
  visit(remark().parse(proposal.body), (node) => {
    if (node.type !== "link" && node.type !== "definition") return
    if (/^(?:[a-z][a-z0-9+.-]*:|#|\/\/)/i.test(node.url)) return
    const start = node.position?.start.offset
    const end = node.position?.end.offset
    if (start === undefined || end === undefined) return
    const url = new URL(node.url, `https://1hive.org/${proposal.file}`)
    const localFile = url.pathname.slice(1)
    const target = (
      sourcePattern.test(localFile) ? `${localFile.slice(0, -3)}${url.search}${url.hash}` : url.href
    )
      .replaceAll("(", "%28")
      .replaceAll(")", "%29")
    const title = node.title
      ? ` "${node.title.replaceAll("\\", "\\\\").replaceAll('"', '\\"')}"`
      : ""
    let value: string
    if (node.type === "definition") {
      value = `[${node.label ?? node.identifier}]: <${target}>${title}`
    } else {
      const labelStart = node.children[0]?.position?.start.offset
      const labelEnd = node.children.at(-1)?.position?.end.offset
      const label =
        labelStart !== undefined && labelEnd !== undefined
          ? proposal.body.slice(labelStart, labelEnd)
          : ""
      value = `[${label}](${target}${title})`
    }
    replacements.push({ start, end, value })
  })
  let body = proposal.body
  for (const { start, end, value } of replacements.sort((a, b) => b.start - a.start)) {
    body = body.slice(0, start) + value + body.slice(end)
  }
  return body
}

export function renderProposal(proposal: Proposal): string {
  const m = proposal.metadata
  const body = resolveProposalLinks(proposal).replace(/^# [^\n]+\n+/, "")
  return (
    frontmatter({
      title: m.title,
      description: m.summary,
      created: m.created,
      updated: m.updated,
      tags: ["proposals"],
    }) +
    `[[proposals/index|All proposals]] · [[Improvement proposals|About the working-draft process]] · [Markdown source](https://1hive.org/${proposal.file})\n\n` +
    `${text(m.summary)}\n\n` +
    `## Record\n\n` +
    `- **ID:** ${m.id === "unassigned" ? "Unassigned" : m.id}\n` +
    `- **Document stage:** ${stages[m.stage].label}\n` +
    `- **Scope:** ${text(m.scope)}\n` +
    `- **Delivery owner:** ${text(m.owner)}\n` +
    `- **Created:** ${m.created}\n- **Updated:** ${m.updated}\n` +
    `${statusLine("Decision", m.decision, decisionLabels)}\n` +
    `- **Decision authority:** ${text(m.decision.authority)}\n` +
    `${statusLine("Funding", m.funding, fundingLabels)}\n` +
    `${statusLine("Delivery", m.delivery, deliveryLabels)}\n\n` +
    `Document maturity, decisions, funding, and delivery are separate records. Publication or a repository merge does not approve a proposal, allocate funds, or authorize a governance action. These records are not live status; verify linked evidence and current rules.\n\n${body}\n`
  )
}

export function renderIndex(proposals: Proposal[]): string {
  const updated = proposals
    .map((p) => p.metadata.updated)
    .sort()
    .at(-1)
  let result =
    frontmatter({
      title: "Proposal index",
      description:
        "Browse repository improvement proposals by document stage, with decisions, funding, and delivery recorded separately.",
      showFolderListing: false,
      ...(updated ? { updated } : {}),
    }) +
    `Browse proposals by **document stage**. A stable document is not necessarily accepted or funded. Each proposal records its decision, funding, and delivery separately.\n\n` +
    `**Process status: working draft.** These are repository improvement records, not a live on-chain proposal feed or an adopted DAO-wide policy. Verify current decisions at their linked sources.\n\n` +
    `[[Improvement proposals|When to use a proposal]] · [Drafting guide](https://1hive.org/proposals/README.md) · [Copy the template](https://1hive.org/proposals/TEMPLATE.md)\n\n` +
    `${proposals.length} proposal${proposals.length === 1 ? "" : "s"} recorded.\n\n`
  for (const [stage, { label, description }] of Object.entries(stages)) {
    const entries = proposals.filter((p) => p.metadata.stage === stage)
    result += `## ${label}\n\n${description}\n\n`
    if (!entries.length) result += "No proposals at this stage.\n\n"
    for (const p of entries) {
      const m = p.metadata
      result +=
        `### [${m.id === "unassigned" ? "Unassigned" : m.id}: ${text(m.title)}](${p.slug})\n\n${text(m.summary)}\n\n` +
        `- **Scope:** ${text(m.scope)}\n` +
        `- **Decision:** ${decisionLabels[m.decision.status]} · **Funding:** ${fundingLabels[m.funding.status]} · **Delivery:** ${deliveryLabels[m.delivery.status]}\n` +
        `- **Updated:** ${m.updated} · **Owner:** ${text(m.owner)}\n\n`
    }
  }
  return result
}

export async function generateProposals(
  root = process.cwd(),
  resources: readonly string[] = agentResources,
  contentDirectory = "content",
): Promise<string[]> {
  const proposals = await readProposals(root, resources)
  const directory = path.resolve(root, contentDirectory, "proposals")
  const pages = new Map<string, string>([
    ["index.md", renderIndex(proposals)],
    ...proposals.map((p) => [path.basename(p.file), renderProposal(p)] as [string, string]),
  ])
  await mkdir(directory, { recursive: true })
  if (!(await lstat(directory)).isDirectory())
    throw new Error(`${directory}: generated directory must not be a symlink`)
  const existing = await readdir(directory)
  // Never overwrite or delete a hand-authored file, symlink, or directory.
  for (const name of existing) {
    const file = path.join(directory, name)
    if (
      !(await lstat(file)).isFile() ||
      !(await readFile(file, "utf8")).includes(generatedMarker)
    ) {
      throw new Error(
        `${file}: reserved for generated proposals; move hand-authored content before generating`,
      )
    }
  }
  for (const [name, content] of pages) await writeFile(path.join(directory, name), content)
  for (const name of existing) if (!pages.has(name)) await rm(path.join(directory, name))
  return [...pages.keys()].map((name) => `proposals/${name}`)
}
